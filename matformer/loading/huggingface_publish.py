def _export_weights(raw_weights):
    """Tensors-only, CPU, deduplicated state dict, ready for safetensors.

    Old Lightning checkpoints stored every tensor twice (`model.x` alongside `x`):
    the prefixed duplicates are dropped. Tied weights share storage and are
    written once.
    """
    keys = set(raw_weights.keys())
    exported, seen = {}, set()
    for key, value in raw_weights.items():
        if not torch.is_tensor(value):
            continue
        if key.startswith("model.") and key[len("model."):] in keys:
            continue
        if value.data_ptr() in seen:
            continue
        seen.add(value.data_ptr())
        exported[key] = value.detach().cpu().contiguous()
    if not exported:
        raise ValueError("No tensors found in the checkpoint weights.")
    return exported


def copy_tokenizer_files(configs, output_dir):
    """Copy the tokenizer declared in the configs into the payload so that
    AutoTokenizer.from_pretrained(repo) works out of the box."""
    name = getattr(getattr(configs, "tokenizer", None), "pretrained_name", None)
    if not name:
        warnings.warn("Configs declare no tokenizer: the repo will not provide one.")
        return False
    source = Path(name)
    if not source.is_dir():
        from huggingface_hub import snapshot_download
        try:
            source = Path(snapshot_download(name, allow_patterns=TOKENIZER_FILE_PATTERNS))
        except Exception as error:  # noqa: BLE001 - publishing must not die on tokenizer issues
            warnings.warn(f"Could not fetch tokenizer '{name}' ({error}): "
                          "the repo will not provide one.")
            return False
    copied = False
    for pattern in TOKENIZER_FILE_PATTERNS:
        for f in source.glob(pattern):
            shutil.copy(f, Path(output_dir) / f.name)
            copied = True
    if not copied:
        warnings.warn(f"No tokenizer files found in {source}.")
    return copied


def build_hub_payload(checkpoint, output_dir, configs=None, model_type="auto",
                      include_tokenizer=True, clean=True, repo_id=None):
    """Build a HuggingFace-ready folder from any Matformer-readable checkpoint.

    Returns the output_dir. With clean=True the weights are re-exported as
    model.safetensors (no optimizer state, no pickles); otherwise the original
    checkpoint file is copied as-is.
    """
    from safetensors.torch import save_file
    from matformer.loading.utils import make_holder

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    holder = make_holder(str(checkpoint), map_location="cpu")
    configs = configs if configs is not None else holder.get_configs()
    if configs is None or not hasattr(configs, "model"):
        raise ValueError(f"{checkpoint} carries no Matformer configs; pass configs=... "
                         "or use a checkpoint saved by Matformer.")
    if model_type == "auto":
        model_type = detect_model_type(configs)
    if model_type not in ("causal", "masked", "sequence", "token"):
        raise ValueError(f"Unknown model_type '{model_type}'.")

    if clean:
        save_file(_export_weights(dict(holder.get_weights())),
                  str(output_dir / WEIGHTS_FILENAME))
        checkpoint_file = WEIGHTS_FILENAME
    else:
        checkpoint_file = Path(checkpoint).name
        shutil.copy(checkpoint, output_dir / checkpoint_file)

    save_matformer_yaml(configs, output_dir / MATFORMER_CONFIG_FILENAME)

    hf_config = MatformerConfig(
        matformer_config_file=MATFORMER_CONFIG_FILENAME,
        checkpoint_file=checkpoint_file,
        auto_map=_auto_map([model_type]),
    ).sync_from_matformer(configs)
    # Manual write: PretrainedConfig.save_pretrained would copy/rewrite auto_map toward the
    # config class's defining module (see integration save_pretrained notes).
    (output_dir / "config.json").write_text(
        json.dumps(hf_config.to_dict(), indent=2, sort_keys=True) + "\n")

    (output_dir / MODELING_FILENAME).write_text(create_modeling_file())
    (output_dir / "README.md").write_text(
        create_readme(repo_id or hf_config.matformer_model_name or "matformer-model",
                      model_type,
                      tokenizer_name=getattr(
                          getattr(configs, "tokenizer", None), "pretrained_name", None)))
    if include_tokenizer:
        copy_tokenizer_files(configs, output_dir)
    # The chat template rides as its own file (the convention transformers now prefers over an
    # inline tokenizer_config entry), so AutoTokenizer picks it up and Matformer re-reads it too.
    template = holder.get_chat_template()
    if template:
        (output_dir / "chat_template.jinja").write_text(template, encoding="utf-8")
    return output_dir


def push_to_hub(checkpoint, repo_id, token=None, private=False, model_type="auto",
                configs=None, include_tokenizer=True, clean=True, commit_message=None):
    """Push a Matformer checkpoint to the hub as a HF-compatible model repo."""
    from huggingface_hub import HfApi, create_repo

    with tempfile.TemporaryDirectory(prefix="matformer_hub_") as tmp:
        build_hub_payload(checkpoint, tmp, configs=configs, model_type=model_type,
                          include_tokenizer=include_tokenizer, clean=clean, repo_id=repo_id)
        create_repo(repo_id, token=token, private=private, exist_ok=True)
        HfApi(token=token).upload_folder(
            folder_path=tmp, repo_id=repo_id, token=token,
            commit_message=commit_message or "Upload Matformer model")
    print(f"Model pushed to https://huggingface.co/{repo_id}")
    return repo_id


def upload_to_huggingface(checkpoint, config=None, hf_name=None, hf_token=None,
                          weights_only=True, model_type="auto", **ignored):
    """Deprecated alias of push_to_hub (old integration signature)."""
    if hf_name is None:
        raise ValueError("hf_name (the repo id) is required.")
    configs = None
    if config:
        from matformer.matformer_configs import MatformerConfigs
        configs = MatformerConfigs.create_configs(config) if isinstance(config, (str, Path)) else config
    return push_to_hub(checkpoint, hf_name, token=hf_token, model_type=model_type,
                       configs=configs, clean=weights_only)


def main():
    import argparse

    parser = argparse.ArgumentParser(
        description="Publish a Matformer checkpoint to HuggingFace.")
    parser.add_argument("--checkpoint", required=True,
                        help="Matformer checkpoint (.ckpt / weights+yaml folder)")
    parser.add_argument("--repo_id", default=None, help="Target hub repo, e.g. user/model")
    parser.add_argument("--token", default=None, help="HuggingFace token (or HF_TOKEN env)")
    parser.add_argument("--out", default=None,
                        help="Only build the payload into this local folder, don't push")
    parser.add_argument("--config", default=None,
                        help="Extra YAML/JSON Matformer config merged over the checkpoint's")
    parser.add_argument("--model_type", default="auto",
                        choices=["auto", "causal", "masked", "sequence", "token"])
    parser.add_argument("--no_tokenizer", action="store_true",
                        help="Don't copy tokenizer files into the repo")
    parser.add_argument("--keep_checkpoint", action="store_true",
                        help="Push the original .ckpt instead of a clean safetensors export")
    parser.add_argument("--private", action="store_true")
    args = parser.parse_args()

    configs = None
    if args.config:
        from matformer.matformer_configs import MatformerConfigs
        configs = MatformerConfigs.create_configs(args.config)

    if args.out:
        build_hub_payload(args.checkpoint, args.out, configs=configs,
                          model_type=args.model_type,
                          include_tokenizer=not args.no_tokenizer,
                          clean=not args.keep_checkpoint)
        print(f"Payload built in {args.out}")
        return
    if not args.repo_id:
        parser.error("--repo_id is required unless --out is used")
    push_to_hub(args.checkpoint, args.repo_id, token=args.token, private=args.private,
                model_type=args.model_type, configs=configs,
                include_tokenizer=not args.no_tokenizer, clean=not args.keep_checkpoint)


if __name__ == "__main__":
    main()
