"""
Publish a Matformer checkpoint to a HuggingFace repository.

The payload built here makes a Matformer repo usable with the usual HF tutorials:

    config.json              light config (model_type "matformer") + auto_map
    modeling_matformer.py    remote-code shim importing matformer.loading.huggingface_integration
    matformer.yaml           the real Matformer configuration
    model.safetensors        weights in Matformer's stable-state-dict format
    README.md                model card with copy-paste usage examples
    tokenizer files          (optional) copied from the checkpoint's tokenizer

Nothing needs to be loaded into a model to publish: the checkpoint is read
through the Matformer checkpoint holder, so any source the framework can read
(.ckpt, weights + YAML folder, legacy Lightning checkpoints) can be published.

Library use:

    from matformer.loading.huggingface_publish import push_to_hub
    push_to_hub("/path/to/model.ckpt", "user/model", token="hf_...")

CLI:

    python -m matformer.loading.huggingface_publish \
        --checkpoint /path/to/model.ckpt --repo_id user/model [--token hf_...]

    # build the payload locally without pushing (no credentials needed):
    python -m matformer.loading.huggingface_publish \
        --checkpoint /path/to/model.ckpt --out ./hf_payload
"""
import json
import shutil
import tempfile
import warnings
from pathlib import Path

import torch

from matformer.loading.huggingface_integration import (
    MATFORMER_CONFIG_FILENAME,
    MODELING_FILENAME,
    PUBLISH_EXCLUDED_SECTIONS,
    WEIGHTS_FILENAME,
    MatformerConfig,
    _auto_map,
    save_matformer_yaml,
)

MODELING_GIT_URL = "git+https://github.com/mrinaldi97/matformer.git"
TOKENIZER_FILE_PATTERNS = [
    "tokenizer.json", "tokenizer_config.json", "special_tokens_map.json",
    "added_tokens.json", "vocab.txt", "vocab.json", "merges.txt",
    "spiece.model", "sentencepiece.bpe.model", "tokenizer.model",
    "chat_template.jinja",
]


def detect_model_type(configs):
    """Infer the HF task ('causal', 'masked', 'sequence', 'token') from Matformer configs."""
    model = configs.model
    if hasattr(model, "scope"):
        return "token" if model.scope == "token" else "sequence"
    model_class = (getattr(model, "model_class", None) or "").lower()
    objective = (getattr(model, "training_objective", None) or "").lower()
    if "autoregressive" in model_class or objective in ("autoregressive", "causal", "next_token", "clm"):
        return "causal"
    if "bert" in model_class or objective in ("masked", "mlm"):
        return "masked"
    if getattr(model, "is_causal", None) is False:
        return "masked"
    return "causal"


def create_modeling_file():
    """Content of the remote-code shim pushed into the HF repo."""
    return f'''# {MODELING_FILENAME}
# Auto-generated by Matformer: lets HuggingFace load this model with
# trust_remote_code=True. It only re-exports Matformer's own HF classes.
import os
import sys

matformer_root = os.getenv("MATFORMER_ROOT")
if matformer_root:
    matformer_root = os.path.abspath(os.path.expanduser(matformer_root))
    if matformer_root not in sys.path:
        sys.path.insert(0, matformer_root)

try:
    from matformer.loading.huggingface_integration import (
        MatformerConfig,
        MatformerModel,
        MatformerForCausalLM,
        MatformerForMaskedLM,
        MatformerForSequenceClassification,
        MatformerForTokenClassification,
        register_matformer,
    )
except ImportError as import_error:
    raise ImportError(
        "This model requires Matformer. Install it with:\\n"
        f"  pip install {MODELING_GIT_URL}\\n"
        "or point the MATFORMER_ROOT environment variable to a local checkout."
    ) from import_error

register_matformer()
'''


