# matformer/gui/taskpage.py
"""One page per task type (the Tasks group in the navigator comes from the local registry).
The session is server-wide — pages drive the same model, each switching the active task — but
every page keeps its own transcript. The parameter panel is generated by the server from the
task's own dataclass (task.fields). Classification and masking results render as interactive
cells: shaded by confidence, hover shows the top-5, clicking a token pulls the FULL distribution
from the server (task.probs -> Table) into a modal — the TUI prints the same rows with str().
Generation streams token events; Enter sends, Shift+Enter newlines, Stop interrupts."""
import tkinter as tk
from tkinter import ttk

from matformer.gui.explorer import pick
from matformer.gui.forms import Form
from matformer.gui.widgets import (Console, Page, ScrollBox, TableList, popup, show_payload,
                                   tooltip, dismiss)

ATTENTION = ["", "sdpa", "flash", "flash_kv", "flashinfer"]


class TaskPage(Page):
    """Drive one task type over the server: parameters, streaming, interactive results."""

    def __init__(self, app, parent, spec):
        super().__init__(app, parent, spec["title"].capitalize(), "no model loaded")
        self.task_type = spec.get("task_type", "generation")
        self.busy, self.live, self._switched = False, None, False
        self._cells, self._stream_mark = [], None
        self._watchdog, self._release_job = None, None
        self.index = spec["id"].replace(":", "")
        self.title_ = spec["title"].capitalize()
        self._build_bar()
        pan = ttk.PanedWindow(self.body, orient="horizontal")
        pan.pack(fill="both", expand=True)
        self._build_center(pan)
        self._build_right(pan)

    # ── load bar (session is global: visible on every task page for convenience) ──
    def _build_bar(self):
        bar = ttk.Frame(self.body)
        bar.pack(fill="x", pady=(0, 4))
        ttk.Label(bar, text="Model:").pack(side="left")
        self.model = ttk.Entry(bar)
        self.model.pack(side="left", fill="x", expand=True, padx=3)
        ttk.Button(bar, text="…", width=2, command=lambda: self._pick(self.model, ())).pack(side="left")
        ttk.Label(bar, text="Cfg:").pack(side="left", padx=(8, 0))
        self.cfg = ttk.Entry(bar, width=22)
        self.cfg.pack(side="left", padx=3)
        ttk.Button(bar, text="…", width=2,
                   command=lambda: self._pick(self.cfg, (".yaml", ".yml"))).pack(side="left")
        ttk.Label(bar, text="Attn:").pack(side="left", padx=(8, 0))
        self.attn = ttk.Combobox(bar, values=ATTENTION, state="readonly", width=9)
        self.attn.set("")
        self.attn.pack(side="left")
        self.load_btn = ttk.Button(bar, text="Load model", style="Accent.TButton", command=self.load)
        self.load_btn.pack(side="left", padx=8)

    def _pick(self, entry, exts):
        p = pick(self.app, self, "", exts, None, "Choose a file on the server")
        if p:
            entry.delete(0, "end")
            entry.insert(0, p)

    # ── transcript + prompt ─────────────────────────────────────────────────────
    def _build_center(self, pan):
        mid = ttk.Frame(pan)
        pan.add(mid, weight=3)
        bottom = ttk.Frame(mid)
        bottom.pack(side="bottom", fill="x", pady=(4, 0))
        self.view = Console(self.app, mid)
        self.view.pack(fill="both", expand=True)
        self.box = tk.Text(bottom, height=3, wrap="word", font=("TkFixedFont", 9), padx=8, pady=6)
        self.box.pack(side="left", fill="x", expand=True)
        self.box.bind("<Return>", self._key_return)
        self.box.bind("<Shift-Return>", lambda e: None)          # default newline
        self.box.bind("<Escape>", lambda e: self.stop())
        side = ttk.Frame(bottom)
        side.pack(side="left", fill="y", padx=(6, 0))
        self.send_btn = ttk.Button(side, text="Send", style="Accent.TButton", command=self.send)
        self.send_btn.pack(fill="x")
        ttk.Button(side, text="Run dataset", command=self.run_task).pack(fill="x", pady=2)
        ttk.Button(side, text="Annotate…", command=self.annotate).pack(fill="x")
        row = ttk.Frame(side)
        row.pack(fill="x", pady=2)
        ttk.Button(row, text="Clear ctx", width=7, style="Ghost.TButton",
                   command=lambda: self._do("task.clear")).pack(side="left")
        ttk.Button(row, text="Ctx", width=4, style="Ghost.TButton",
                   command=lambda: self._do("task.context")).pack(side="left", padx=3)
        self.view.text.bind("<Button-3>", self._transcript_menu)

    def _key_return(self, e):
        if self.box.index("insert").split(".")[1] and self.busy:
            return
        self.send()
        return "break"

    def _transcript_menu(self, e):
        m = tk.Menu(self, tearoff=0)
        m.add_command(label="Copy all", command=lambda: self.app.copy(self.view.text.get("1.0", "end-1c")))
        m.add_command(label="Clear", command=self.view.clear)
        popup(m, e.x_root, e.y_root)

    # ── parameters dock (server-driven) ─────────────────────────────────────────
    def _build_right(self, pan):
        right = ttk.Frame(pan)
        pan.add(right, weight=2)
        head = ttk.Frame(right)
        head.pack(fill="x")
        ttk.Label(head, text="Parameters", style="Head.TLabel").pack(side="left")
        ttk.Button(head, text="Apply", command=self.apply).pack(side="right")
        ttk.Button(head, text="Reload", width=6, style="Ghost.TButton", command=self.fields).pack(side="right", padx=3)
        self.scroll = ScrollBox(self.app, right)
        self.scroll.pack(fill="both", expand=True, pady=3)
        self.form_holder = ttk.Frame(self.scroll.inner)
        self.form_holder.pack(fill="x")
        self.form = None
        ttk.Button(right, text="Model info", style="Ghost.TButton", command=self.model_info).pack(anchor="w")
        self.info = Console(self.app, right)
        self.info.pack(fill="x")
        self.info.text.configure(height=6)

    # ── server round-trips ──────────────────────────────────────────────────────
    def server(self):
        return self.app.server

    def activated(self):
        self._sync()

    def server_changed(self):
        self._sync()

    def task_state(self, st):
        """Pushed by the server whenever the session changes on ANY page."""
        if not st.get("loaded"):
            self.set_subtitle("no model loaded")
            self.state_busy(False)
            if self.form:
                for w in self.form_holder.winfo_children():
                    w.destroy()
                self.form = None
            return
        self.set_subtitle(f"{st.get('source')}   ·   active task: {st.get('task')}"
                          + (f"   ·   sweep: {st['sweep']}" if st.get("sweep") else "")
                          + (f"   ·   {st['sweeps']}-run sweep declared"
                             if st.get("sweeps", 0) > 1 and not st.get("sweep") else "")
                          + ("" if st.get("task") == self.task_type else "   (this page will switch it)"))

    def sweep(self):
        """The points the loaded configs declare, and the choice of running the session on one of
        them. The model stays on the GPU: switching rewrites the run around it (and the names its
        outputs are written under), so a task sweep is a click, not a reload -- for as long as the
        sweep does not reach the model itself, which the server says so."""
        SweepMenu(self)

    def _sync(self):
        self.server().call("task.state", None, self._state)

    def _state(self, st):
        if not st or isinstance(st, tuple):
            return
        self.task_state(st)
        if not st.get("loaded"):
            return
        if st.get("task") != self.task_type and not self._switched \
                and self.app.pages.get(self.app.current) is self:
            self._switched = True
            self.server().call("task.use", {"name": self.task_type}, lambda r: self.fields())
        elif self.form is None:
            self.fields()

    def load(self):
        self.load_btn.configure(state="disabled", text="Loading…")
        self.set_subtitle("loading model…")
        cfg = [c.strip() for c in self.cfg.get().split(",") if c.strip()]
        self.server().call("task.load", {"model": self.model.get().strip() or None, "cfg": cfg,
                                         "attention": self.attn.get() or None,
                                         "task": self.task_type}, self._loaded)

    def _loaded(self, st):
        self.load_btn.configure(state="normal", text="Load model")
        if not st:
            return
        self._switched = True
        self.fields()

    def fields(self):
        def done(schema):
            if schema and not isinstance(schema, tuple):
                for w in self.form_holder.winfo_children():
                    w.destroy()
                self.form = Form(self.app, self.form_holder, schema["fields"])
                self.form.pack(fill="x")
        self.server().call("task.fields", None, done)

    def apply(self):
        if not self.form:
            return
        for name, value in self.form.values().items():
            self.server().call("task.set", {"path": name, "value": value})
        self.app.toast("task parameters applied")

    # ── run a text ──────────────────────────────────────────────────────────────
    def send(self):
        text = self.box.get("1.0", "end").strip()
        if not text or self.busy:
            return
        self.box.delete("1.0", "end")
        self.view.put(f"you> {text}\n", "you")
        self.busy, self.live = True, self.app.server_var.get()
        self.state_busy(True)
        self.server().call("task.feed", {"text": text}, self._done)

    def state_busy(self, busy):
        self.send_btn.configure(state="normal", text="Stop" if busy else "Send",
                                style="Danger.TButton" if busy else "Accent.TButton",
                                command=self.stop if busy else self.send)

    def stop(self):
        """Ask the server to interrupt, and never wait on it forever: if nothing comes back within
        a few seconds the page releases itself, so a dead request cannot lock the UI."""
        if not self.busy:
            return
        self.server().call("task.stop", None, lambda r: None)
        if self._release_job:
            self.after_cancel(self._release_job)
        self._release_job = self.after(4000, lambda: self._release("stopped"))

    def _release(self, note=None):
        if not self.busy:
            return
        self.busy = False
        if self._release_job:
            self.after_cancel(self._release_job)
            self._release_job = None
        if self._watchdog:
            self.after_cancel(self._watchdog)
            self._watchdog = None
        self.state_busy(False)
        if note:
            self.view.put(f"  ({note})\n", "meta")

    def _done(self, r):
        self._release()
        if not r or isinstance(r, tuple):
            return                      # the error itself was already toasted and logged
        cells = r.get("cells")
        if cells:
            self._render_cells(cells, r.get("rendered"))
        elif r.get("rendered"):
            self.view.put(r["rendered"] + "\n")
        if r.get("status"):
            self.view.put(f"  {r['status']}\n\n", "status")
        if r.get("reason") == "stopped":
            self.view.put("  (stopped)\n", "meta")

    def _render_cells(self, cells, streamed=None):
        """Prediction strip: one tag per cell, background shaded by 1-p (surface=sure, red=unsure),
        hover -> the candidates, click -> the full distribution. A streamed generation is replaced
        by its own strip once it is over: the text you watched appear becomes the thing you click,
        without the transcript carrying it twice."""
        if streamed and self._stream_mark:
            try:
                self.view.text.delete(self._stream_mark, "end-1c")
            except tk.TclError:
                pass
        self._stream_mark = None
        p = self.app.palette()
        self._cells = cells
        for i, c in enumerate(cells):
            tag = f"{self.index}cell{i}"
            shade = _blend(p["surface"], p["err_soft"], min(1.0, (1 - c["p"]) * 2.2))
            self.view.text.tag_configure(tag, background=shade,
                                         foreground=p["text"],
                                         borderwidth=1, relief="solid")
            self.view.text.tag_bind(tag, "<Enter>",
                                    lambda e, c=c: tooltip(
                                        f"{c['tok']}  →  {c['label']} {c['p']:.0%}\n" +
                                        "\n".join(f"{n} {q:.0%}" for n, q in c["top"][1:]),
                                        e.x_root, e.y_root))
            self.view.text.tag_bind(tag, "<Leave>", lambda e: dismiss())
            self.view.text.tag_bind(tag, "<Button-1>", lambda e, i=i: self._cell_detail(i))
            self.view.text.tag_bind(tag, "<Button-3>", lambda e, i=i: self._cell_menu(e, i))
            self.view.put(c["tok"] + (" " if not c["tok"].endswith((" ", "\n")) else ""), tag)
        self.view.put("\n")

    def _cell_menu(self, e, index):
        cell = self._cells[index]
        m = tk.Menu(self, tearoff=0)
        m.add_command(label=f"Distribution of «{cell['tok']}»", command=lambda: self._cell_detail(index))
        m.add_command(label="Top-k of every token", command=self.show_details)
        m.add_command(label="Copy token", command=lambda: self.app.copy(cell["tok"]))
        m.add_separator()
        m.add_command(label="Keep more candidates…", command=self.detail_knobs)
        popup(m, e.x_root, e.y_root)

    def detail_knobs(self):
        """How much of the distribution to keep: the speed/detail trade-off is the user's, so it is
        one click here and a parameter on the panel, never a decision made for him."""
        m = tk.Menu(self, tearoff=0)
        for label, value in (("off — fastest", 0), ("top 5", 5), ("top 25", 25),
                             ("every class / whole vocabulary", -1)):
            m.add_command(label=label, command=lambda v=value: self._set_k(v))
        popup(m, self.winfo_pointerx(), self.winfo_pointery())

    def _set_k(self, value):
        self.server().call("task.set", {"path": "topk_present", "value": value},
                           lambda r: (self.app.toast(f"topk_present = {value}"), self.fields()))

    def _cell_detail(self, index):
        cell = self._cells[index]
        dlg = tk.Toplevel(self.app)
        dlg.title(f"{cell['tok']}   →   {cell['label']}")
        dlg.geometry("460x520")
        dlg.transient(self.app)
        head = ttk.Frame(dlg)
        head.pack(fill="x", padx=10, pady=(10, 4))
        ttk.Label(head, text=f"«{cell['tok']}»", style="Head.TLabel").pack(side="left")
        self.stats_line = ttk.Label(head, style="Muted.TLabel")
        self.stats_line.pack(side="left", padx=10)
        holder = ttk.Frame(dlg)
        holder.pack(fill="both", expand=True, padx=10)
        bottom = ttk.Frame(dlg)
        bottom.pack(fill="x", padx=10, pady=8)
        ttk.Button(bottom, text="Close", command=dlg.destroy).pack(side="right")
        ttk.Button(bottom, text="Copy", style="Ghost.TButton",
                   command=lambda: self.app.copy(self._detail_text)).pack(side="right", padx=4)
        ttk.Button(bottom, text="Top-k of every token", style="Ghost.TButton",
                   command=self.show_details).pack(side="left")

        def got(payload):
            if not payload or isinstance(payload, tuple):
                show_payload(self.app, holder, payload or "no distribution stored")
                return
            stats = payload.get("stats") or {}
            self._detail_text = "  ".join(f"{k}: {v}" for k, v in stats.items())
            self.stats_line.configure(text=self._detail_text)
            table = payload.get("distribution")
            if table and table.get("__table__"):
                table = dict(table, columns=list(table["columns"]) + [""],
                             rows=[dict(r, **{"": _bars(r.get("prob"))}) for r in table["rows"]])
            show_payload(self.app, holder, table)
        self.server().call("task.probs", {"index": cell.get("index", index), "top": 50}, got)
        dlg.bind("<Escape>", lambda e: dlg.destroy())

    def show_details(self):
        """The whole run as a table: one row per position, its candidates. What the strip cannot
        show at a glance, the table can."""
        def got(payload):
            if not payload:
                return
            if isinstance(payload, tuple):
                return self.app.toast(payload[1], error=True)
            dlg = tk.Toplevel(self.app)
            dlg.title(f"{self.title_} — token detail")
            dlg.geometry("900x520")
            dlg.transient(self.app)
            show_payload(self.app, dlg, payload)
            ttk.Button(dlg, text="Close", command=dlg.destroy).pack(anchor="e", padx=8, pady=6)
            dlg.bind("<Escape>", lambda e: dlg.destroy())
        self.server().call("task.details", None, got)

    def run_task(self):
        self.view.put("running the task over its dataset…\n", "meta")
        self.server().call("task.run", None, lambda r: r and
                           self.view.put((r.get("text") or "(no summary)") + "\n\n", "status"))

    def annotate(self):
        path = pick(self.app, self, "", (".jsonl", ".json", ".csv"), None, "File to annotate")
        if path:
            self.server().call("task.annotate", {"input": path},
                               lambda r: r and self.view.put(
                                   f"{r.get('rows')} rows -> {r.get('output')}\n\n", "status"))

    def _do(self, method, *args):
        self.server().call(method, {"args": list(args)},
                           lambda r: r and self.view.put(str(r.get("text", "")) + "\n", "meta"))

    def model_info(self):
        self.server().call("task.info", None,
                           lambda r: r and (self.info.clear(), self.info.put(r["text"])))

    # ── events ──────────────────────────────────────────────────────────────────
    def on_event(self, server, name, data):
        if name == "token" and self.live == server and self.busy \
                and data.get("task", self.task_type) == self.task_type:
            self.view.put(data.get("t", ""))


class SweepMenu(tk.Toplevel):
    """The points the loaded configs declare, on top of the model that is already on the GPU.

    Picking a point rewrites the run around that model -- its task, its data, the names its
    outputs are written under -- so comparing two points is two clicks, not two loads. A sweep
    that reaches the sections a model is built from is said so and left to run_task.py and the
    training queue, which do build one model per point."""

    def __init__(self, page):
        super().__init__(page)
        self.page, self.app = page, page.app
        self.title("Sweep of the loaded configs")
        self.geometry("700x400")
        self.minsize(520, 260)
        self.transient(page)
        self.head = ttk.Label(self, text="reading the sweep…", style="Muted.TLabel")
        self.head.pack(side="top", fill="x", padx=10, pady=(10, 2))
        bottom = ttk.Frame(self)
        bottom.pack(side="bottom", fill="x", padx=10, pady=8)
        ttk.Button(bottom, text="Run on this point", style="Accent.TButton",
                   command=self._apply).pack(side="right", padx=4)
        ttk.Button(bottom, text="No point (plain configs)", style="Ghost.TButton",
                   command=lambda: self._apply(None)).pack(side="right")
        ttk.Button(bottom, text="Close", style="Ghost.TButton", command=self.destroy).pack(side="left")
        self.table = TableList(self.app, self, on_double=lambda row: self._apply(row), height=12)
        self.table.headings(["#", "point", "what it changes"])
        self.table.fill([], "reading…")
        self.table.pack(fill="both", expand=True, padx=10, pady=4)
        self.bind("<Escape>", lambda e: self.destroy())
        self._ask()

    def _ask(self):
        def got(payload):
            if not payload or isinstance(payload, tuple):
                return
            runs = payload.get("runs") or 0
            self.head.config(text=(f"{runs} runs over {', '.join(payload['dimensions'])}"
                                   if runs > 1 else "these configs declare no sweep")
                             + ("   ·   this sweep changes the model itself: run it from "
                                "run_task.py or the training queue"
                                if runs > 1 and payload.get("crosses_model") else ""))
            self.table.fill([{"#": one["index"], "point": one["name"], "what": one["describe"]}
                             for one in payload.get("points") or []],
                            "no sweep: the loaded configs are one run")
        self.page.server().call("task.sweeps", None, got)

    def _apply(self, row):
        point = None if row is None else row["point"]
        self.page.server().call("task.sweep", {"point": point}, self._switched)

    def _switched(self, answer):
        if not answer or isinstance(answer, tuple):
            return self.app.toast(answer[1] if isinstance(answer, tuple) else "the server refused",
                                  error=True)
        self.app.toast(f"run switched to {answer['sweep'] or 'the plain configs'}")
        self.destroy()


def _bars(probability):
    """A text bar beside a probability: the table becomes readable at a glance."""
    try:
        filled = int(round(float(probability) * 18))
    except (TypeError, ValueError):
        return ""
    return "▰" * filled + "▱" * (18 - filled)


def _blend(c1, c2, t):
    """Linear blend of two #rrggbb colors."""
    a, b = _rgb(c1), _rgb(c2)
    return "#%02x%02x%02x" % tuple(int(x + (y - x) * t) for x, y in zip(a, b))


def _rgb(c):
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))
