# matformer/gui/taskpage.py
"""One page per task type (the Tasks group in the navigator comes from the local registry).
The session is server-wide — pages drive the same model, each switching the active task — but
every page keeps its own transcript. The parameter panel is generated by the server from the
task's own dataclass (task.fields). Classification and masking results render as interactive
cells: shaded by confidence, hover shows the top-5, clicking a token pulls the FULL distribution
from the server (task.probs -> Table) into a modal — the TUI prints the same rows with str().
Generation streams token events; Enter sends, Shift+Enter newlines, Stop interrupts."""
import tkinter as tk
from tkinter import ttk

from matformer.gui import exports
from matformer.gui.analysis import AnalysisView
from matformer.gui.explorer import pick
from matformer.gui.forms import Form
from matformer.gui.wizard import WizardDialog
from matformer.gui.widgets import (Console, Page, ScrollBox, TableList, popup, show_payload,
                                   tooltip, dismiss)

ATTENTION = ["", "sdpa", "flash", "flash_kv", "flashinfer"]


def _plain(text):
    """Token or label -> what a human reads: byte-level spaces/newlines become spaces/newlines."""
    return (str(text).replace("\u0120", " ").replace("Ġ", " ").replace("▁", " ")
            .replace("Ċ", "\n").replace("ĉ", "\t"))


class TaskPage(Page):
    """Drive one task type over the server: parameters, streaming, interactive results."""

    def __init__(self, app, parent, spec):
        super().__init__(app, parent, spec["title"].capitalize(), "no model loaded")
        self.task_type = spec.get("task_type", "generation")
        self.busy, self.live, self._switched = False, None, False
        self._cells, self._stream_mark = [], None
        self.show_prompt = tk.BooleanVar(value=False)   # show the exact chat-templated prompt
        self._watchdog, self._release_job = None, None
        self._info_done = False
        self._has_model = False
        self.index = spec["id"].replace(":", "")
        self.title_ = spec["title"].capitalize()
        self._build_bar()
        self._banner = ttk.Label(self.body, text="", style="Warn.TLabel")
        self._banner.pack(fill="x")
        self._build_actions()
        pan = ttk.PanedWindow(self.body, orient="horizontal")
        pan.pack(fill="both", expand=True)
        self._build_center(pan)
        self._build_right(pan)

    # ── load bar (session is global: visible on every task page for convenience) ──
    def _build_bar(self):
        bar = ttk.Frame(self.body)
        bar.pack(fill="x", pady=(0, 4))
        ttk.Label(bar, text="Model:").pack(side="left")
        self.model = ttk.Entry(bar)
        self.model.pack(side="left", fill="x", expand=True, padx=3)
        ttk.Button(bar, text="…", width=2, command=lambda: self._pick(self.model, ())).pack(side="left")
        ttk.Label(bar, text="Cfg:").pack(side="left", padx=(8, 0))
        self.cfg = ttk.Entry(bar, width=22)
        self.cfg.pack(side="left", padx=3)
        ttk.Button(bar, text="…", width=2,
                   command=lambda: self._pick(self.cfg, (".yaml", ".yml"))).pack(side="left")
        ttk.Label(bar, text="Attn:").pack(side="left", padx=(8, 0))
        self.attn = ttk.Combobox(bar, values=ATTENTION, state="readonly", width=9)
        self.attn.set("")
        self.attn.pack(side="left")
        self.load_btn = ttk.Button(bar, text="Load model", style="Accent.TButton", command=self.load)
        self.load_btn.pack(side="left", padx=8)

    def _build_actions(self):
        ttk.Button(self.actions, text="Table", style="Ghost.TButton",
                   command=lambda: self.center_tabs.select(self.table_frame)
                   ).pack(side="left", padx=2)
        ttk.Button(self.actions, text="Token detail", style="Ghost.TButton",
                   command=self.show_details).pack(side="left", padx=2)
        detail = ttk.Menubutton(self.actions, text="Candidates", style="Ghost.TButton")
        menu = tk.Menu(detail, tearoff=0)
        for label, value in (("off", 0), ("top 5", 5), ("top 25", 25), ("all", -1)):
            menu.add_command(label=label, command=lambda v=value: self._set_k(v))
        detail["menu"] = menu
        detail.pack(side="left", padx=2)
        ttk.Button(self.actions, text="Annotate…", style="Ghost.TButton",
                   command=lambda: WizardDialog(self.app, "annotate")
                   ).pack(side="left", padx=2)
        self._chat_button = ttk.Menubutton(self.actions, text="Chat", style="Ghost.TButton")
        self._chat_menu = tk.Menu(self._chat_button, tearoff=0)
        self._chat_button["menu"] = self._chat_menu
        self._chat_button.pack(side="left", padx=2)
        self._chat_button.bind("<Button-1>", lambda e: self._refresh_chat_menu())
        export = ttk.Menubutton(self.actions, text="Export", style="Ghost.TButton")
        menu = tk.Menu(export, tearoff=0)
        menu.add_command(label="Transcript…", command=self.export_transcript)
        menu.add_command(label="Table…", command=self.export_table)
        menu.add_command(label="Generation tokens…", command=self.export_tokens)
        menu.add_command(label="Analysis…", command=lambda: self.analysis.export())
        export["menu"] = menu
        export.pack(side="left", padx=2)

    def export_transcript(self):
        text = self.view.text.get("1.0", "end-1c")
        if not text.strip():
            return self.app.toast("the transcript is empty", error=True)
        path = exports.ask("Export the transcript", f"{self.task_type}-transcript.txt",
                           exports.TEXT_FORMATS)
        if path:
            exports.write_text(path, text, f"{self.title_} transcript")
            self.app.toast(f"saved {path}")

    def export_table(self):
        rows = self.result_table.rows
        if not rows:
            return self.app.toast("the table is empty", error=True)
        path = exports.ask("Export the table", f"{self.task_type}-table.csv")
        if path:
            exports.write_rows(path, rows, self.result_table.columns,
                               f"{self.title_} table")
            self.app.toast(f"saved {path}")

    def export_tokens(self):
        rows = [{"position": i, "token": c.get("tok"), "prediction": c.get("label"),
                 "probability": c.get("p"),
                 "candidates": "  ".join(f"{name} {q:.4g}" for name, q in (c.get("top") or [])[1:])}
                for i, c in enumerate(self._cells)]
        if not rows:
            return self.app.toast("no token detail to export", error=True)
        path = exports.ask("Export generated tokens", f"{self.task_type}-tokens.csv")
        if path:
            exports.write_rows(path, rows, title=f"{self.title_} token detail")
            self.app.toast(f"saved {path}")

    def system_prompt(self):
        from tkinter.simpledialog import askstring
        value = askstring("System prompt", "System prompt:", parent=self)
        if value is not None:
            self._do("task.system", value)

    def chat_template(self):
        from tkinter.simpledialog import askstring
        value = askstring("Chat template", "Template (on/off, or inline Jinja/.jinja path):",
                          parent=self)
        if value is not None:
            self._do("task.template", value)

    def _refresh_chat_menu(self):
        """Populate the Chat menu from the server: whether the model has a template, the toggles it
        reads (enable_thinking, ...), and the current use/system settings. Kept out of the way when
        unused: a model without a template simply disables the button."""
        def got(state):
            if not state or isinstance(state, tuple):
                return
            menu = self._chat_menu
            menu.delete(0, "end")
            available = state.get("available")
            self._chat_button.configure(state="normal" if available else "disabled")
            if not available:
                menu.add_command(label="no chat template for this model", state="disabled")
                return
            use = state.get("use")
            menu.add_command(label=f"{'✓ ' if use else '   '}Use chat template",
                             command=lambda: self._chat_set({"use": not use}))
            menu.add_command(label="System prompt…", command=self.system_prompt)
            menu.add_separator()
            self.show_prompt.set(bool(self.show_prompt.get()))
            menu.add_checkbutton(label="Show templated prompt", variable=self.show_prompt)
            features = state.get("features") or []
            if features:
                menu.add_separator()
                options = state.get("options") or {}
                for feature in features:
                    var = tk.BooleanVar(value=bool(options.get(feature, True)))
                    menu.add_checkbutton(
                        label=f"Template: {feature}", variable=var,
                        command=lambda f=feature, v=var, o=dict(options): self._chat_set(
                            {"options": {**o, f: v.get()}}))
        self.server().call("task.chat", None, got)

    def _chat_set(self, payload):
        def done(result):
            if result and not isinstance(result, tuple):
                self.app.toast("chat settings updated")
        self.server().call("task.chat", payload, done)

    def _pick(self, entry, exts):
        p = pick(self.app, self, "", exts, None, "Choose a file on the server")
        if p:
            entry.delete(0, "end")
            entry.insert(0, p)

