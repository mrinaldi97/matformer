        pan.add(mid, weight=3)
        bottom = ttk.Frame(mid)
        bottom.pack(side="bottom", fill="x", pady=(4, 0))
        self.center_tabs = ttk.Notebook(mid)
        self.center_tabs.pack(fill="both", expand=True)
        self.view = Console(self.app, self.center_tabs)
        self.center_tabs.add(self.view, text="Transcript")
        self.table_frame = ttk.Frame(self.center_tabs)
        self.result_table = TableList(self.app, self.table_frame, height=10,
                                      on_double=self._table_detail)
        self.result_table.headings(["token", "prediction", "probability", "candidates"])
        self.result_table.fill([], "no result yet")
        self.result_table.pack(fill="both", expand=True)
        self.center_tabs.add(self.table_frame, text="Table")
        self.analysis_frame = ttk.Frame(self.center_tabs)
        self.analysis = AnalysisView(self.app, self.analysis_frame)
        self.analysis.pack(fill="both", expand=True)
        self.center_tabs.add(self.analysis_frame, text="Analysis")
        self.box = tk.Text(bottom, height=3, wrap="word", font=("TkFixedFont", 9), padx=8, pady=6)
