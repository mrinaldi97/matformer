        head.pack(fill="x", padx=10, pady=(10, 4))
        ttk.Label(head, text=f"«{cell['tok']}»", style="Head.TLabel").pack(side="left")
        self.stats_line = ttk.Label(head, style="Muted.TLabel")
        self.stats_line.pack(side="left", padx=10)
        holder = ttk.Frame(dlg)
        holder.pack(fill="both", expand=True, padx=10)
        bottom = ttk.Frame(dlg)
        bottom.pack(fill="x", padx=10, pady=8)
        ttk.Button(bottom, text="Close", command=dlg.destroy).pack(side="right")
        ttk.Button(bottom, text="Copy", style="Ghost.TButton",
                   command=lambda: self.app.copy(self._detail_text)).pack(side="right", padx=4)
        ttk.Button(bottom, text="Top-k of every token", style="Ghost.TButton",
                   command=self.show_details).pack(side="left")

        def got(payload):
            if not payload or isinstance(payload, tuple):
                show_payload(self.app, holder, payload or "no distribution stored")
                return
            stats = payload.get("stats") or {}
            self._detail_text = "  ".join(f"{k}: {v}" for k, v in stats.items())
